"""ngspice adapter for the Lab 04 CE voltage-divider amplifier.

This module owns netlist generation, the external process call and parsing of
ngspice ASCII raw output. It never imports Flask and never renders HTML.
All numbers returned here come from an actual ngspice run; nothing is mocked.
"""

import functools
import math
import os
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

MODEL_NAME = "QNPN"
MODEL_CARD = "IS=1e-14 BF=100 VAF=100 RB=10"
MODEL_LINE = f".MODEL {MODEL_NAME} NPN({MODEL_CARD})"
ANALYSES = ("dc", "ac", "tran")
ANALYSIS_LABELS = {
    "dc": "DC · .op",
    "ac": "AC · .ac",
    "tran": "Transient · .tran",
}

# The handout asks for a reproducible model, not a guessed commercial part.
# The parameters above are a generic NPN model declared in every netlist.
KNOWN_ENGINE_PATHS = (
    Path.home() / "AppData/Local/ngspice-47/Spice64/bin/ngspice_con.exe",
    Path("/usr/bin/ngspice"),
    Path("/usr/local/bin/ngspice"),
)


class SpiceEngineError(Exception):
    """Raised when inputs, the engine process or its output are unusable."""


def find_engine():
    """Return an executable path, preferring NGSPICE_EXE then PATH."""
    candidates = []
    env_path = os.environ.get("NGSPICE_EXE")
    if env_path:
        candidates.append(Path(env_path))
    for name in ("ngspice_con", "ngspice"):
        found = shutil.which(name)
        if found:
            candidates.append(Path(found))
    candidates.extend(KNOWN_ENGINE_PATHS)

    for candidate in candidates:
        if candidate.is_file():
            return str(candidate)
    raise SpiceEngineError(
        "ไม่พบ ngspice ใน PATH หรือตำแหน่งที่ติดตั้งไว้ "
        "(ตั้งค่า NGSPICE_EXE หรือรันตาม README เพื่อติดตั้งก่อน)"
    )


@functools.lru_cache(maxsize=1)
def engine_version(executable):
    """Read the version banner once per executable."""
    try:
        proc = subprocess.run(
            [executable, "-v"],
            capture_output=True,
            text=True,
            timeout=10,
            shell=False,
        )
    except (OSError, subprocess.SubprocessError):
        return "unknown"
    match = re.search(r"ngspice-([0-9.]+)", proc.stdout + proc.stderr)
    return match.group(1) if match else "unknown"


def _number(raw, label, *, minimum=None, maximum=None):
    try:
        value = float(raw)
    except (TypeError, ValueError):
        raise SpiceEngineError(f"กรุณากรอก {label} เป็นตัวเลข") from None
    if not math.isfinite(value):
        raise SpiceEngineError(f"{label} ต้องเป็นตัวเลขที่จำกัดค่า (ไม่ใช่ NaN/Inf)")
    if minimum is not None and value < minimum:
        raise SpiceEngineError(f"{label} ต้องมากกว่าหรือเท่ากับ {minimum:g}")
    if maximum is not None and value > maximum:
        raise SpiceEngineError(f"{label} ต้องไม่เกิน {maximum:g}")
    return value


def validate_params(raw):
    """Validate form values and return ohms/farads/volts/hertz as floats."""
    if raw.get("analysis") not in ANALYSES:
        raise SpiceEngineError("Analysis Mode ไม่รู้จัก (เลือก DC, AC หรือ Transient)")

    params = {
        "analysis": raw["analysis"],
        "vcc": _number(raw.get("vcc"), "VCC", minimum=0.000001),
        "r1": _number(raw.get("r1"), "R1", minimum=0.000001),
        "r2": _number(raw.get("r2"), "R2", minimum=0.000001),
        "rc": _number(raw.get("rc"), "RC", minimum=0.000001),
        "re": _number(raw.get("re"), "RE", minimum=0.000001),
        "rl": _number(raw.get("rl"), "RL", minimum=0.000001),
        "cin": _number(raw.get("cin"), "Cin", minimum=0.000000001),
        "cout": _number(raw.get("cout"), "Cout", minimum=0.000000001),
        "amp": _number(raw.get("amp"), "Amplitude", minimum=0.000000001),
        "freq": _number(raw.get("freq"), "Frequency", minimum=1, maximum=1e9),
    }
    if params["amp"] > params["vcc"]:
        raise SpiceEngineError("Amplitude ต้องไม่เกิน VCC")
    return params


def _fmt(value):
    return f"{value:.10g}"


def build_netlist(params, analysis):
    """Create one complete CE voltage-divider netlist for the chosen analysis."""
    if analysis == "tran":
        source = f"VS IN 0 SIN(0 {_fmt(params['amp'])} {_fmt(params['freq'])})"
    else:
        source = f"VS IN 0 DC 0 AC {_fmt(params['amp'])}"

    lines = [
        "* CE voltage-divider amplifier - generated by spice_engine.py",
        f"VCC VCC 0 DC {_fmt(params['vcc'])}",
        f"R1 VCC BASE {_fmt(params['r1'])}",
        f"R2 BASE 0 {_fmt(params['r2'])}",
        f"RC VCC COLL {_fmt(params['rc'])}",
        f"RE EMIT 0 {_fmt(params['re'])}",
        f"RL OUT 0 {_fmt(params['rl'])}",
        "Q1 COLL BASE EMIT " + MODEL_NAME,
        f"CIN IN BASE {_fmt(params['cin'])}",
        f"COUT COLL OUT {_fmt(params['cout'])}",
        source,
        MODEL_LINE,
    ]

    if analysis == "dc":
        lines.append(".OP")
    elif analysis == "ac":
        # Fixed sweep shows the coupling-capacitor low-frequency corner.
        # The generic model has no high-frequency pole, so fH may be
        # "not determined in sweep range" and must not be invented.
        lines.append(".AC DEC 20 1 10MEG")
    elif analysis == "tran":
        stop = 6.0 / params["freq"]  # six source periods
        step = stop / 1000.0
        lines.append(f".TRAN {_fmt(step)} {_fmt(stop)} 0 {_fmt(step)}")
    else:
        raise SpiceEngineError("Analysis Mode ไม่รู้จัก")

    lines.append(".END")
    return "\n".join(lines) + "\n"


def parse_raw_ascii(text):
    """Parse ngspice ASCII raw output into (points, variables, metadata)."""
    lines = text.splitlines()
    values_at = None
    for index, line in enumerate(lines):
        if line.strip() == "Values:":
            values_at = index
            break
    if values_at is None:
        raise SpiceEngineError("ไฟล์ผล ngspice ไม่มีส่วน Values: (output ผิดรูปแบบ)")

    header = "\n".join(lines[:values_at])
    count_match = re.search(r"No\.\s*Variables:\s*(\d+)", header)
    if not count_match:
        raise SpiceEngineError("ไฟล์ผล ngspice ไม่ระบุ No. Variables")
    expected = int(count_match.group(1))

    flags_match = re.search(r"Flags:\s*(.*)", header)
    flags = flags_match.group(1).strip().lower() if flags_match else ""

    variables = []
    inside_variables = False
    for line in lines[:values_at]:
        if line.strip() == "Variables:":
            inside_variables = True
            continue
        if not inside_variables:
            continue
        parts = line.split()
        if len(parts) >= 2:
            variables.append(parts[1].lower())

    def parse_value(token):
        if "," in token:
            real, imag = token.split(",", 1)
            return complex(float(real), float(imag))
        return float(token)

    points = []
    current = []
    for line in lines[values_at + 1:]:
        parts = line.split()
        if not parts:
            continue
        if parts[0].isdigit() and len(parts) >= 2:
            if current:
                points.append(current)
            current = [parse_value(value) for value in parts[1:]]
        elif not current:
            current = [parse_value(value) for value in parts]
        else:
            current.extend(parse_value(value) for value in parts)
    if current:
        points.append(current)

    if not points:
        raise SpiceEngineError("ngspice ไม่เขียนข้อมูลผลลัพธ์ (output ว่าง)")
    if any(len(point) != expected for point in points):
        raise SpiceEngineError("ข้อมูลผล ngspice ไม่ตรงกับ No. Variables")
    return points, variables, {"flags": flags, "expected": expected}


def _as_float(value):
    return float(value.real if isinstance(value, complex) else value)


def _as_complex(value):
    return value if isinstance(value, complex) else complex(value, 0.0)


def _index(variables, name):
    try:
        return variables.index(name.lower())
    except ValueError:
        raise SpiceEngineError(f"ngspice ไม่ส่งตัวแปร {name} ในผลลัพธ์") from None


def operating_point(points, variables, params):
    """Read node voltages and derive IC from the collector resistor drop."""
    values = points[0]
    vb = _as_float(values[_index(variables, "v(base)")])
    ve = _as_float(values[_index(variables, "v(emit)")])
    vc = _as_float(values[_index(variables, "v(coll)")])
    ic = (params["vcc"] - vc) / params["rc"]
    return {
        "vb": vb,
        "ve": ve,
        "vc": vc,
        "vce": vc - ve,
        "ic": ic,
        "source": "ngspice .op node voltages; IC derived from (VCC-VC)/RC",
    }


def _wrap_degrees(angle):
    while angle > 180.0:
        angle -= 360.0
    while angle < -180.0:
        angle += 360.0
    return angle


def frequency_response(points, variables):
    """Return gain/phase referred to V(IN), not the internal base node."""
    f_index = _index(variables, "frequency")
    in_index = _index(variables, "v(in)")
    out_index = _index(variables, "v(out)")
    series = []
    previous = None
    for point in points:
        frequency = abs(_as_complex(point[f_index]))
        vin = _as_complex(point[in_index])
        vout = _as_complex(point[out_index])
        if abs(vin) == 0.0:
            continue
        ratio = vout / vin
        gain_db = 20.0 * math.log10(abs(ratio))
        phase = math.degrees(math.atan2(ratio.imag, ratio.real))
        if previous is not None:
            while phase - previous > 180.0:
                phase -= 360.0
            while phase - previous < -180.0:
                phase += 360.0
        previous = phase
        series.append(
            {
                "freq_hz": frequency,
                "gain_db": gain_db,
                "phase_deg": _wrap_degrees(phase),
            }
        )
    if not series:
        raise SpiceEngineError("ผล .ac ไม่มีจุดข้อมูลที่ใช้คำนวณ Gain ได้")
    return series


def transient_response(points, variables):
    """Return time/Vin/Vout samples and a measured inversion indicator."""
    t_index = _index(variables, "time")
    in_index = _index(variables, "v(in)")
    out_index = _index(variables, "v(out)")
    series = [
        {
            "time_s": _as_float(point[t_index]),
            "vin_v": _as_float(point[in_index]),
            "vout_v": _as_float(point[out_index]),
        }
        for point in points
    ]
    tail = series[-max(1, len(series) // 5):]
    mean_in = sum(item["vin_v"] for item in tail) / len(tail)
    mean_out = sum(item["vout_v"] for item in tail) / len(tail)
    covariance = sum(
        (item["vin_v"] - mean_in) * (item["vout_v"] - mean_out) for item in tail
    )
    summary = {
        "vin_peak_v": max(abs(item["vin_v"]) for item in tail),
        "vout_peak_v": (max(item["vout_v"] for item in tail)
                        - min(item["vout_v"] for item in tail)) / 2.0,
        "inverted": covariance < 0.0,
        "samples": len(series),
    }
    return series, summary


def run_analysis(raw_params, timeout=30):
    """Run one verified ngspice analysis and return parsed, sourced results."""
    params = validate_params(raw_params)
    analysis = params["analysis"]
    executable = find_engine()
    version = engine_version(executable)
    netlist = build_netlist(params, analysis)

    with tempfile.TemporaryDirectory(prefix="bjt_lab4_") as workdir:
        directory = Path(workdir)
        (directory / "circuit.cir").write_text(netlist, encoding="utf-8")
        command = [
            executable,
            "-b",
            "-o", "run.log",
            "-r", "run.raw",
            "circuit.cir",
        ]
        try:
            proc = subprocess.run(
                command,
                cwd=directory,
                capture_output=True,
                text=True,
                timeout=timeout,
                shell=False,
            )
        except subprocess.TimeoutExpired:
            raise SpiceEngineError(f"ngspice ใช้เวลาเกิน {timeout} วินาที (timeout)") from None
        except OSError as exc:
            raise SpiceEngineError(f"เรียก ngspice ไม่ได้: {exc}") from None

        log_path = directory / "run.log"
        raw_path = directory / "run.raw"
        log_text = log_path.read_text(encoding="utf-8", errors="replace") if log_path.exists() else ""
        if proc.returncode != 0:
            raise SpiceEngineError(
                f"ngspice run failed (code {proc.returncode}): "
                + (log_text[-1200:] or proc.stderr[-1200:])
            )
        if not raw_path.is_file() or raw_path.stat().st_size == 0:
            raise SpiceEngineError("ngspice ไม่สร้างไฟล์ผลลัพธ์ (.raw ว่างหรือไม่มี)")

        points, variables, meta = parse_raw_ascii(
            raw_path.read_text(encoding="utf-8", errors="replace")
        )

    result = {
        "status": "success",
        "engine": "ngspice",
        "version": version,
        "model": MODEL_LINE,
        "model_card": MODEL_CARD,
        "analysis": analysis,
        "analysis_label": ANALYSIS_LABELS[analysis],
        "netlist": netlist,
        "log_excerpt": log_text[:1500],
        "flags": meta["flags"],
    }

    if analysis == "dc":
        result["readings"] = operating_point(points, variables, params)
        result["series"] = []
    elif analysis == "ac":
        result["series"] = frequency_response(points, variables)
        result["readings"] = {"points": len(result["series"])}
    else:
        series, summary = transient_response(points, variables)
        result["series"] = series
        result["readings"] = summary
    return result
